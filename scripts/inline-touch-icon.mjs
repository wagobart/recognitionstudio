// Puts the iPhone home-screen icon inside index.html as a data: URI.
// Why: on iOS 26 the "Add to Home Screen" sheet often fails to download the
// icon from the network and shows a plain letter tile instead (seen on
// apple.com too). With the image inside the page there is nothing to download.
// Run after regenerating public/apple-touch-icon-v2.png:  node scripts/inline-touch-icon.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pngPath = join(root, 'public', 'apple-touch-icon-v2.png');
const htmlPath = join(root, 'public', 'index.html');

const b64 = readFileSync(pngPath).toString('base64');
const block =
  '<!-- touch-icon:start (generated by scripts/inline-touch-icon.mjs) -->\n' +
  `<link rel="apple-touch-icon" sizes="180x180" href="data:image/png;base64,${b64}">\n` +
  '<!-- touch-icon:end -->';

let html = readFileSync(htmlPath, 'utf8');
const marked = /<!-- touch-icon:start[^>]*-->[\s\S]*?<!-- touch-icon:end -->/;
const plain = /<link rel="apple-touch-icon"[^>]*>/;
if (marked.test(html)) html = html.replace(marked, block);
else if (plain.test(html)) html = html.replace(plain, block);
else throw new Error('No apple-touch-icon link found in public/index.html');

writeFileSync(htmlPath, html);
console.log(`Inlined touch icon (${b64.length} base64 chars) into public/index.html`);
